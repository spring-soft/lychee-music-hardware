const PCB1 = '197f3e3cc67e949b';
const p = await eda.dmt_Pcb.getAllPcbsInfo();
await eda.dmt_EditorControl.openDocument(PCB1);
await new Promise(r=>setTimeout(r,4000));
const f = await eda.pcb_ManufactureData.getGerberFile();
if (!f) return { err: 'getGerberFile 返回空' };
const buf = await f.arrayBuffer();
const bytes = new Uint8Array(buf);
let bin = '';
const CH = 0x8000;
for (let i = 0; i < bytes.length; i += CH) bin += String.fromCharCode.apply(null, bytes.subarray(i, i+CH));
return { name: f.name, size: f.size, type: f.type, 字节数: bytes.length, b64: btoa(bin) };
